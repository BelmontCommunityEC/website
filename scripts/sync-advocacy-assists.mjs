#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '..');
const metricsFilePath = path.join(repoRoot, 'src/data/advocacy-metrics.ts');

// Source of truth is the server-verified counter (Netlify Function + Blobs).
// Override the endpoint with ADVOCACY_ASSIST_ENDPOINT, or the site with SITE_URL.
const siteUrl = (process.env.SITE_URL?.trim() || 'https://belmontcommunityec.org.au').replace(/\/$/, '');
const endpoint = process.env.ADVOCACY_ASSIST_ENDPOINT?.trim() || `${siteUrl}/api/advocacy-assist`;

const checkMode = process.argv.includes('--check');

function toNumber(value) {
  const n = Number(value);
  return Number.isFinite(n) ? n : 0;
}

function buildMetricsFile(snapshot) {
  return `export type AdvocacyMetricsSnapshot = {\n  asOfDate: string;\n  advocacyAssistsTotal: number;\n  campaignAssists: Record<string, number>;\n};\n\n// Auto-generated by scripts/sync-advocacy-assists.mjs\nexport const advocacyMetrics: AdvocacyMetricsSnapshot = {\n  asOfDate: '${snapshot.asOfDate}',\n  advocacyAssistsTotal: ${snapshot.advocacyAssistsTotal},\n  campaignAssists: {\n    'protect-a-tree': ${snapshot.campaignAssists['protect-a-tree']},\n  },\n};\n`;
}

async function main() {
  const response = await fetch(endpoint, {
    headers: { Accept: 'application/json' },
  });

  if (!response.ok) {
    const body = await response.text();
    throw new Error(`Advocacy assist endpoint failed (${response.status}): ${body}`);
  }

  const payload = await response.json();
  const campaigns =
    payload && typeof payload.campaigns === 'object' && payload.campaigns !== null
      ? payload.campaigns
      : {};

  const advocacyAssistsTotal = toNumber(payload?.total);
  const campaignAssists = {
    'protect-a-tree': toNumber(campaigns['protect-a-tree']),
  };

  const snapshot = {
    asOfDate: new Date().toISOString().slice(0, 10),
    advocacyAssistsTotal,
    campaignAssists,
  };

  const nextContent = buildMetricsFile(snapshot);

  if (checkMode) {
    const currentContent = fs.readFileSync(metricsFilePath, 'utf8');
    if (currentContent !== nextContent) {
      console.error('Advocacy metrics snapshot is out of date.');
      process.exit(1);
    }

    console.log('Advocacy metrics snapshot is up to date.');
    return;
  }

  fs.writeFileSync(metricsFilePath, nextContent, 'utf8');
  console.log(
    `Updated ${path.relative(repoRoot, metricsFilePath)} with ${advocacyAssistsTotal} total assists (protect-a-tree: ${campaignAssists['protect-a-tree']}).`,
  );
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exit(1);
});
